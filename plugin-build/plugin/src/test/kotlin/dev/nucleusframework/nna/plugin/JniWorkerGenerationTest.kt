package dev.nucleusframework.nna.plugin

import org.gradle.testkit.runner.GradleRunner
import org.gradle.testkit.runner.TaskOutcome
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder
import java.io.File

/**
 * Runs JNI generation through the real isolated Gradle Worker, proving the `knePsiScope`
 * classpath wiring resolves KotlinPoet (and kotlin-compiler-embeddable) for the generator
 * (design D5 of unify-codegen-kotlinpoet-drop-ffm). It also pins the JNI-only surface:
 * generation succeeds without any bridgeMode setting, and the legacy `-Pkne.bridgeMode`
 * property fails the build with a configuration-time error.
 */
class JniWorkerGenerationTest {

    @get:Rule
    val testProjectDir = TemporaryFolder()

    @Test
    fun `generation runs through the isolated worker with KotlinPoet on the classpath`() {
        writeConsumerProject()
        val result = GradleRunner.create()
            .withProjectDir(testProjectDir.root)
            .withArguments("generateKneNativeBridges", "--stacktrace")
            .forwardOutput()
            .build()

        assertEquals(TaskOutcome.SUCCESS, result.task(":generateKneNativeBridges")?.outcome)
        assertTrue(
            "worker must parse and generate, was:\n${result.output}",
            result.output.contains("Parsed") && result.output.contains("kne: Updated"),
        )
        // KotlinPoet-shaped output: the generated bridge carries the KotlinPoet header comment
        // and the JVM proxies were written under the configured package.
        val bridges = File(testProjectDir.root, "build/generated/kne/nativeBridges/native_bridges.kt")
        assertTrue("native bridge must exist", bridges.isFile)
        assertTrue(
            "bridge must be KotlinPoet output (file comment header)",
            bridges.readText().startsWith("// Auto-generated by kotlin-native-export plugin. Do not modify."),
        )
        // Sources are split per business class: the shared runtime file plus one class file.
        val classBridge = File(testProjectDir.root, "build/generated/kne/nativeBridges/native_Repro_bridges.kt")
        assertTrue("per-class bridge file must exist", classBridge.isFile)
        assertTrue(
            "per-class bridge file must hold the class entry points",
            classBridge.readText().contains("native_Repro_ping("),
        )
        val proxy = File(testProjectDir.root, "build/generated/kne/jvmProxies/com/example/Repro.kt")
        assertTrue("JVM proxy must exist", proxy.isFile)
    }

    @Test
    fun `legacy bridgeMode property fails with a clear error`() {
        writeConsumerProject()
        val result = GradleRunner.create()
            .withProjectDir(testProjectDir.root)
            .withArguments("help", "-Pkne.bridgeMode=ffm")
            .forwardOutput()
            .buildAndFail()

        assertTrue(
            "legacy property must be rejected, was:\n${result.output}",
            result.output.contains("JNI is the only bridge backend"),
        )
    }

    private fun writeConsumerProject() {
        val root = testProjectDir.root
        val pluginBuildDir = File(System.getProperty("nna.pluginBuildDir")).invariantSeparatorsPath
        File(root, "settings.gradle.kts").writeText(
            """
            pluginManagement {
                includeBuild("$pluginBuildDir")
                repositories {
                    gradlePluginPortal()
                    mavenCentral()
                    google()
                }
            }
            dependencyResolutionManagement {
                repositories {
                    mavenCentral()
                    google()
                }
            }
            rootProject.name = "jni-worker-consumer"
            """.trimIndent(),
        )
        File(root, "build.gradle.kts").writeText(
            """
            plugins {
                kotlin("multiplatform") version "2.4.20"
                id("dev.nucleusframework.nna")
            }

            kotlin {
                jvm()
                $hostNativeTarget
            }

            kotlinNativeExport {
                nativeLibName = "repro"
            }
            """.trimIndent(),
        )
        val nativeSrc = File(root, "src/nativeMain/kotlin/com/example")
        nativeSrc.mkdirs()
        File(nativeSrc, "Repro.kt").writeText(
            """
            package com.example

            class Repro(val initial: Int) {
                fun ping(): String = "ok"
                suspend fun slowPing(): String = "slow-ok"
            }
            """.trimIndent(),
        )
    }

    private val hostNativeTarget: String
        get() {
            val hostOs = System.getProperty("os.name")
            return when {
                hostOs == "Mac OS X" -> "macosArm64()"
                hostOs == "Linux" -> "linuxX64()"
                hostOs.startsWith("Windows") -> "mingwX64()"
                else -> error("Unsupported host OS: $hostOs")
            }
        }
}
