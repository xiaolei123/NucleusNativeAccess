    private fun StringBuilder.generateRuntime(
        module: KneModule,
        pkg: String,
        callbackSignatures: Set<KneType.FUNCTION>,
        functionReturnTypes: List<KneType.FUNCTION>,
        hasSuspend: Boolean,
        hasFlow: Boolean,
    ) {
        line("// Auto-generated by kotlin-native-export plugin. Do not modify.")
        line("package $pkg")
        line()
        line("import java.lang.ref.Cleaner")
        line("import java.nio.file.Files")
        line("import java.nio.file.Paths")
        line("import java.nio.file.StandardCopyOption")
        if (hasSuspend) {
            line("import kotlin.coroutines.resume")
            line("import kotlin.coroutines.resumeWithException")
            line("import kotlinx.coroutines.CancellableContinuation")
        }
        if (hasSuspend || hasFlow) {
            line("import kotlinx.coroutines.CancellationException")
            line("import kotlinx.coroutines.channels.awaitClose")
            line("import kotlinx.coroutines.flow.Flow")
            line("import kotlinx.coroutines.flow.callbackFlow")
            line("import kotlinx.coroutines.runBlocking")
            line("import kotlinx.coroutines.suspendCancellableCoroutine")
        }
        line()
        line("/**")
        line(" * Shared JNI runtime: loads the native shared library, triggers JNI native-method")
        line(" * registration (RegisterNatives bootstrap) and manages object lifecycle.")
        line(" *")
        line(" * No java.lang.foreign APIs are used; runs on JDK 8+ and Android JVMs.")
        line(" */")
        line("internal object KneRuntime {")
        line()
        line("    private const val LIB_NAME = \"${module.libName}\"")
        line("    @Volatile")
        line("    private var nativesRegistered = false")
        line("    private val registrationLock = Any()")
        line()
        line("    /** Idempotent: loads the library and registers every native method exactly once. */")
        line("    fun ensureNativesRegistered(): Boolean {")
        line("        if (!nativesRegistered) {")
        line("            synchronized(registrationLock) {")
        line("                if (!nativesRegistered) {")
        line("                    loadLibrary()")
        line("                    initNatives()")
        line("                    nativesRegistered = true")
        line("                }")
        line("            }")
        line("        }")
        line("        return true")
        line("    }")
        line()
        line("    /** Bound during bootstrap: the JVM resolves it by symbol name via dlsym. */")
        line("    private external fun initNatives()")
        line()
        line("    private fun loadLibrary() {")
        line("        val fileName = System.mapLibraryName(LIB_NAME)")
        line()
        line("        // Tier 1: explicit paths (java.library.path, working dir, packaged apps)")
        line("        val sep = if (System.getProperty(\"os.name\").lowercase().contains(\"win\")) \";\" else \":\"")
        line("        val basePaths = System.getProperty(\"java.library.path\", \"\").split(sep)")
        line("        val extraDirs = mutableListOf(System.getProperty(\"user.dir\", \".\"))")
        line("        for (dir in (basePaths + extraDirs).distinct().filter { it.isNotBlank() }) {")
        line("            val file = Paths.get(dir, fileName).toFile()")
        line("            if (file.exists()) { System.load(file.absolutePath); return }")
        line("            val libFile = Paths.get(dir, \"lib\", fileName).toFile()")
        line("            if (libFile.exists()) { System.load(libFile.absolutePath); return }")
        line("        }")
        line()
        line("        // Tier 2: standard library path resolution (Android jniLibs, installed dirs)")
        line("        try {")
        line("            System.loadLibrary(LIB_NAME)")
        line("            return")
        line("        } catch (_: UnsatisfiedLinkError) {")
        line("            // fall through to JAR extraction")
        line("        }")
        line()
        line("        // Tier 3: extract from JAR resources to a persistent cache (zero-config desktop)")
        line("        val platform = detectPlatform()")
        line("        val resourcePath = \"/kne/native/\$platform/\$fileName\"")
        line("        val stream = KneRuntime::class.java.getResourceAsStream(resourcePath)")
        line("        if (stream != null) {")
        line("            val cacheDir = resolveCacheDir(platform)")
        line("            Files.createDirectories(cacheDir)")
        line("            val target = cacheDir.resolve(fileName)")
        line("            stream.use { input ->")
        line("                val bytes = input.readAllBytes()")
        line("                val stale = !Files.exists(target) ||")
        line("                    Files.size(target) != bytes.size.toLong() ||")
        line("                    !Files.readAllBytes(target).contentEquals(bytes)")
        line("                if (stale) {")
        line("                    val tmp = Files.createTempFile(cacheDir, LIB_NAME, \".tmp\")")
        line("                    Files.write(tmp, bytes)")
        line("                    Files.move(tmp, target, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE)")
        line("                }")
        line("            }")
        line("            System.load(target.toFile().absolutePath)")
        line("            return")
        line("        }")
        line()
        line("        throw UnsatisfiedLinkError(\"Native library not found: \$fileName\")")
        line("    }")
        line()
        line("    private fun detectPlatform(): String {")
        line("        val os = System.getProperty(\"os.name\", \"\").lowercase()")
        line("        val arch = System.getProperty(\"os.arch\").let { if (it == \"aarch64\" || it == \"arm64\") \"aarch64\" else \"x64\" }")
        line("        val osName = when { os.contains(\"mac\") || os.contains(\"darwin\") -> \"darwin\"; os.contains(\"win\") -> \"win32\"; else -> \"linux\" }")
        line("        return \"\$osName-\$arch\"")
        line("    }")
        line()
        line("    private fun resolveCacheDir(platform: String): java.nio.file.Path {")
        line("        val os = System.getProperty(\"os.name\", \"\").lowercase()")
        line("        val base = when {")
        line("            os.contains(\"mac\") -> Paths.get(System.getProperty(\"user.home\"), \"Library\", \"Caches\")")
        line("            os.contains(\"win\") -> Paths.get(System.getenv(\"LOCALAPPDATA\") ?: System.getProperty(\"user.home\"))")
        line("            else -> Paths.get(System.getenv(\"XDG_CACHE_HOME\") ?: \"\${System.getProperty(\"user.home\")}/.cache\")")
        line("        }")
        line("        return base.resolve(\"kne\").resolve(\"native\").resolve(platform)")
        line("    }")
        line()
        line("    // ── Object lifecycle ─────────────────────────────────────────────────")
        line()
        line("    /** Disposal action for a proxy; captures only the native handle so the proxy stays collectable. */")
        line("    fun disposer(handle: Long): () -> Unit = {")
        line("        runCatching { KneNativeBindings._kneDisposeRef(handle) }")
        line("    }")
        line()
        emitLease()
        line()

        // Mirrors the FFM backend: an object passed as an argument must not be disposed while the
        // native call still uses its handle, and a closed one must fail loudly on the caller side.
        line("    /** Keeps an object passed as an argument alive (not disposable) for the duration of a call. */")
        line("    inline fun <T> leased(lease: Lease?, block: () -> T): T {")
        line("        lease?.acquire()")
        line("        try {")
        line("            return block()")
        line("        } finally {")
        line("            lease?.release()")
        line("        }")
        line("    }")
        line()

        // Same contract as the FFM backend's cstr(): strings cross as NUL-terminated data on the
        // wire, so an embedded NUL must fail loudly instead of being silently truncated.
        line("    /** Rejects strings with embedded NUL characters (they would be truncated in transit). */")
        line("    fun checkString(value: String): String {")
        line("        require(value.indexOf('\\u0000') < 0) { \"Strings passed to native code cannot contain NUL characters\" }")
        line("        return value")
        line("    }")
        line()

        if (callbackSignatures.isNotEmpty()) {
            line("    // ── Callback dispatchers (native calls these via JNI) ─────────────")
            for (sig in callbackSignatures) {
                emitCallbackDispatcher(sig)
            }
            line()
        }

        if (hasSuspend) {
            line("    // ── Suspend completion dispatchers ─────────────────────────────────")
            suspendReturnTypes(module).forEach { t -> emitSuspendDispatcher(module, t) }
            line()
        }

        if (hasFlow) {
            line("    // ── Flow dispatchers ───────────────────────────────────────────────")
            flowElemTypes(module).forEach { t -> emitFlowDispatcher(module, t) }
            line()
        }

        line("}")
        line()
        line("/** Hosts the common JNI natives (dispose, suspend cancel, flow credits). */")
        line("object KneNativeBindings {")
        line("    private val _kneReg = KneRuntime.ensureNativesRegistered()")
        line()
        line("    @JvmStatic")
        line("    external fun _kneDisposeRef(handle: Long)")
        line()
        if (hasSuspend || hasFlow) {
            line("    @JvmStatic")
            line("    external fun _kneCancelJob(jobHandle: Long)")
            line()
        }
        if (hasFlow) {
            line("    @JvmStatic")
            line("    external fun _kneFlowCredit(jobHandle: Long)")
            line()
        }
        // Invoke bridges for lambdas that native methods return as opaque handles.
        functionReturnTypes.forEach { fnType ->
            val id = JniTypes.functionId(fnType)
            val params = externalParamDeclList(
                fnType.paramTypes.mapIndexed { i, t -> KneParam("p$i", t) },
                leadingHandle = true,
            )
            line("    @JvmStatic")
            line("    external fun _kneInvokeFn$id($params): ${extReturnType(fnType.returnType)}")
            line()
        }
        line("}")
    }

    /** Function types returned by the API surface (need an invoke bridge on both sides). */
    private fun collectFunctionReturnTypes(module: KneModule): List<KneType.FUNCTION> {
        val result = LinkedHashSet<KneType.FUNCTION>()
        fun scan(t: KneType) {
            when (t) {
                is KneType.FUNCTION -> result.add(t)
                is KneType.NULLABLE -> scan(t.inner)
                else -> {}
            }
        }
        module.classes.forEach { cls ->
            cls.methods.forEach { scan(it.returnType) }
            cls.companionMethods.forEach { scan(it.returnType) }
        }
        module.functions.forEach { scan(it.returnType) }
        return result.toList()
    }

    /** The Lease lifecycle, verbatim from the FFM backend (tests depend on its semantics). */
    private fun StringBuilder.emitLease() {
        line("    /**")
        line("     * Guards a native object: counts in-flight calls and defers disposal until the last one ends,")
        line("     * so close() is safe from any thread, including from inside a callback on the same object.")
        line("     */")
        line("    class Lease(private val dispose: () -> Unit) {")
        line("        // Low bits: in-flight calls; CLOSED bit: close requested.")
        line("        private val state = java.util.concurrent.atomic.AtomicInteger(0)")
        line()
        line("        val isClosed: Boolean get() = state.get() and CLOSED != 0")
        line()
        line("        fun acquire() {")
        line("            while (true) {")
        line("                val s = state.get()")
        line("                check(s and CLOSED == 0) { \"Native object has been closed\" }")
        line("                if (state.compareAndSet(s, s + 1)) return")
        line("            }")
        line("        }")
        line()
        line("        fun release() {")
        line("            if (state.decrementAndGet() == CLOSED) dispose()")
        line("        }")
        line()
        line("        fun close() {")
        line("            while (true) {")
        line("                val s = state.get()")
        line("                if (s and CLOSED != 0) return")
        line("                if (state.compareAndSet(s, s or CLOSED)) {")
        line("                    if (s == 0) dispose()")
        line("                    return")
        line("                }")
        line("            }")
        line("        }")
        line()
        line("        inline fun <T> use(block: () -> T): T {")
        line("            acquire()")
        line("            try {")
        line("                return block()")
        line("            } finally {")
        line("                release()")
        line("            }")
        line("        }")
        line()
        line("        private companion object {")
        line("            const val CLOSED = 1 shl 30")
        line("        }")
        line("    }")
    }

    // ── Callback dispatchers ─────────────────────────────────────────────────

    /** Emits `KneFn<id>`: adapts flat JNI payloads into the user lambda's Kotlin signature. */
    private fun StringBuilder.emitCallbackDispatcher(sig: KneType.FUNCTION) {
        val id = callbackId(sig)
        line()
        line("    internal class KneFn$id(@JvmField val fn: ${sig.jvmTypeName}) {")
        val adapted = sig.paramTypes.mapIndexed { i, t -> cbAdaptedParam(t, "p$i") }
        val paramList = adapted.joinToString(", ") { "${it.second}: ${it.first}" }
        val innerArgs = sig.paramTypes.mapIndexed { i, t -> cbAdaptedArg(t, "p$i") }.joinToString(", ")
        when (val rt = sig.returnType) {
            is KneType.UNIT -> line("        fun invoke($paramList) = fn($innerArgs)")
            is KneType.ENUM -> line("        fun invoke($paramList): Int = fn($innerArgs).ordinal")
            is KneType.OBJECT, is KneType.INTERFACE, is KneType.DATA_CLASS ->
                line("        fun invoke($paramList): Any = fn($innerArgs) as Any")
            is KneType.LIST, is KneType.SET -> {
                val elem = if (rt is KneType.LIST) rt.elementType else (rt as KneType.SET).elementType
                line("        fun invoke($paramList): Any = run {")
                line("            val _r = fn($innerArgs)")
                line("            ${cbCollReturnPack(elem, "_r")}")
                line("        }")
            }
            is KneType.MAP -> {
                line("        fun invoke($paramList): Any = run {")
                line("            val _r = fn($innerArgs)")
                line("            arrayOf<Any?>(")
                line("                ${mapPackExpr(rt.keyType, "_r.keys")}!!,")
                line("                ${mapPackExpr(rt.valueType, "_r.values")}!!,")
                line("            )")
                line("        }")
            }
            // Primitives / String / ByteArray: the native side looks the dispatcher up by the
            // *unboxed* signature (e.g. (Ljava/lang/String;)Ljava/lang/String;), so `invoke` must
            // declare the real type — returning `Any` would compile to Ljava/lang/Object; and the
            // GetMethodID lookup would miss.
            is KneType.STRING -> line("        fun invoke($paramList): String = fn($innerArgs)")
            is KneType.BYTE_ARRAY -> line("        fun invoke($paramList): ByteArray = fn($innerArgs)")
            is KneType.BOOLEAN -> line("        fun invoke($paramList): Boolean = fn($innerArgs)")
            is KneType.INT -> line("        fun invoke($paramList): Int = fn($innerArgs)")
            is KneType.LONG -> line("        fun invoke($paramList): Long = fn($innerArgs)")
            is KneType.DOUBLE -> line("        fun invoke($paramList): Double = fn($innerArgs)")
            is KneType.FLOAT -> line("        fun invoke($paramList): Float = fn($innerArgs)")
            is KneType.SHORT -> line("        fun invoke($paramList): Short = fn($innerArgs)")
            is KneType.BYTE -> line("        fun invoke($paramList): Byte = fn($innerArgs)")
            else -> line("        fun invoke($paramList): Any = fn($innerArgs) as Any")
        }
        line("    }")
    }

    /** Packs a returned List/Set into the flat array the native side reads back. */
    private fun cbCollReturnPack(elemType: KneType, expr: String): String = when (elemType) {
        is KneType.INT -> "$expr.toIntArray()"
        is KneType.LONG -> "$expr.toLongArray()"
        is KneType.DOUBLE -> "$expr.toDoubleArray()"
        is KneType.FLOAT -> "$expr.toFloatArray()"
        is KneType.SHORT -> "$expr.toShortArray()"
        is KneType.BYTE -> "$expr.toByteArray()"
        is KneType.BOOLEAN -> "$expr.toBooleanArray()"
        is KneType.ENUM -> "IntArray($expr.size) { $expr[it].ordinal }"
        is KneType.STRING -> "run { val _a = arrayOfNulls<String>($expr.size); $expr.forEachIndexed { i, s -> _a[i] = s }; _a }"
        is KneType.OBJECT -> "LongArray($expr.size) { ($expr[it] as ${elemType.simpleName}).handle }"
        is KneType.INTERFACE -> "LongArray($expr.size) { ($expr[it] as ${elemType.simpleName}).handle }"
        is KneType.BYTE_ARRAY -> "run { val _a = arrayOfNulls<ByteArray>($expr.size); $expr.forEachIndexed { i, b -> _a[i] = b }; _a }"
        is KneType.DATA_CLASS -> "run { val _a = arrayOfNulls<Any>($expr.size); $expr.forEachIndexed { i, v -> _a[i] = v }; _a }"
        else -> "run { val _a = arrayOfNulls<Any>($expr.size); $expr.forEachIndexed { i, v -> _a[i] = v }; _a }"
    }

    /** (declared JVM type, param name) the dispatcher's invoke method exposes to native. */
    private fun cbAdaptedParam(t: KneType, name: String): Pair<String, String> = when (t) {
        is KneType.INT, is KneType.LONG, is KneType.DOUBLE, is KneType.FLOAT,
        is KneType.BYTE, is KneType.SHORT -> t.jvmTypeName to name
        is KneType.BOOLEAN -> "Boolean" to name
        is KneType.STRING -> "String" to name
        is KneType.ENUM -> "Int" to name // ordinal
        is KneType.BYTE_ARRAY -> "ByteArray" to name
        is KneType.OBJECT -> t.simpleName to name // proxy object
        is KneType.INTERFACE -> t.simpleName to name
        is KneType.DATA_CLASS -> t.simpleName to name // JVM object (constructed natively)
        is KneType.LIST -> listAdaptedParam(t.elementType, name)
        is KneType.SET -> listAdaptedParam(t.elementType, name)
        is KneType.MAP -> "Map<${t.keyType.jvmTypeName}, ${t.valueType.jvmTypeName}>" to name
        else -> "Any?" to name
    }

    private fun listAdaptedParam(elemType: KneType, name: String): Pair<String, String> = when (elemType) {
        is KneType.INT -> "IntArray" to name
        is KneType.LONG -> "LongArray" to name
        is KneType.DOUBLE -> "DoubleArray" to name
        is KneType.FLOAT -> "FloatArray" to name
        is KneType.SHORT -> "ShortArray" to name
        is KneType.BYTE -> "ByteArray" to name
        is KneType.BOOLEAN -> "BooleanArray" to name
        is KneType.ENUM -> "IntArray" to name
        is KneType.STRING -> "Array<String?>" to name
        is KneType.OBJECT, is KneType.INTERFACE -> "LongArray" to name
        is KneType.BYTE_ARRAY -> "Array<ByteArray?>" to name
        else -> "Array<Any?>" to name
    }

    /** Expression converting the adapted param into the user-lambda argument. */
    private fun cbAdaptedArg(t: KneType, name: String): String = when (t) {
        is KneType.ENUM -> "${t.simpleName}.entries[$name]"
        is KneType.LIST -> listAdaptedArg(t.elementType, name) + if (t is KneType.LIST) "" else ".toSet()"
        is KneType.SET -> listAdaptedArg(t.elementType, name) + ".toSet()"
        is KneType.MAP -> "($name as Map<${t.keyType.jvmTypeName}, ${t.valueType.jvmTypeName}>)"
        else -> name
    }

    private fun listAdaptedArg(elemType: KneType, name: String): String = when (elemType) {
        is KneType.INT, is KneType.LONG, is KneType.DOUBLE, is KneType.FLOAT,
        is KneType.SHORT, is KneType.BYTE, is KneType.BOOLEAN -> "$name.toList()"
        is KneType.ENUM -> "$name.toList().map { ${elemType.simpleName}.entries[it] }"
        is KneType.STRING -> "$name.map { it ?: \"\" }"
        is KneType.OBJECT -> "$name.map { ${elemType.simpleName}.fromNativeHandle(it) }"
        is KneType.INTERFACE -> "$name.map { ${elemType.simpleName}.fromNativeHandle(it) }"
        is KneType.BYTE_ARRAY -> "$name.map { it ?: ByteArray(0) }"
        is KneType.DATA_CLASS -> "$name.map { it as ${elemType.simpleName} }"
        else -> "$name.toList()"
    }

    /** Packing expression for a Map half when a callback returns a Map. */
    private fun mapPackExpr(t: KneType, expr: String): String = when (t) {
        is KneType.INT -> "IntArray($expr.size) { ($expr.toList()[it] as Int) }"
        is KneType.LONG -> "LongArray($expr.size) { ($expr.toList()[it] as Long) }"
        is KneType.DOUBLE -> "DoubleArray($expr.size) { ($expr.toList()[it] as Double) }"
        is KneType.FLOAT -> "FloatArray($expr.size) { ($expr.toList()[it] as Float) }"
        is KneType.SHORT -> "ShortArray($expr.size) { ($expr.toList()[it] as Short) }"
        is KneType.BYTE -> "ByteArray($expr.size) { ($expr.toList()[it] as Byte) }"
        is KneType.BOOLEAN -> "BooleanArray($expr.size) { ($expr.toList()[it] as Boolean) }"
        is KneType.ENUM -> "IntArray($expr.size) { ($expr.toList()[it] as ${t.simpleName}).ordinal }"
        is KneType.STRING -> "run { val _a = arrayOfNulls<String>($expr.size); $expr.toList().forEachIndexed { i, v -> _a[i] = v }; _a }"
        is KneType.OBJECT -> "LongArray($expr.size) { ($expr.toList()[it] as ${t.simpleName}).handle }"
        is KneType.INTERFACE -> "LongArray($expr.size) { ($expr.toList()[it] as ${t.simpleName}).handle }"
        else -> "run { val _a = arrayOfNulls<Any>($expr.size); $expr.toList().forEachIndexed { i, v -> _a[i] = v }; _a }"
    }

    // ── Suspend dispatchers ──────────────────────────────────────────────────

    private fun suspendReturnTypes(module: KneModule): Set<KneType> {
        val result = mutableSetOf<KneType>()
        fun scan(fn: KneFunction) {
            if (fn.isSuspend) result.add(fn.returnType)
        }
        module.classes.forEach { cls ->
            cls.methods.forEach { scan(it) }
            cls.companionMethods.forEach { scan(it) }
        }
        module.functions.forEach { scan(it) }
        return result
    }

    private fun flowElemTypes(module: KneModule): Set<KneType> {
        val result = mutableSetOf<KneType>()
        fun scan(type: KneType) {
            if (type is KneType.FLOW) result.add(type.elementType)
        }
        module.classes.forEach { cls ->
            cls.methods.forEach { scan(it.returnType) }
            cls.companionMethods.forEach { scan(it.returnType) }
        }
        module.functions.forEach { scan(it.returnType) }
        return result
    }

    /** Emits `KneSuspend<Id>`: JNI completion object resuming the continuation. */
    private fun StringBuilder.emitSuspendDispatcher(module: KneModule, type: KneType) {
        val id = payloadId(type)
        val publicType = type.jvmTypeName
        line()
        line("    internal class KneSuspend$id(")
        line("        private val cont: CancellableContinuation<$publicType>,")
        line("        private val lease: Lease,")
        line("    ) {")
        // Unit suspend functions have no payload: native calls `onSuccess()V` (see
        // _kneSuspendOk_Void), so the JVM overload must take no parameter. Declaring
        // `onSuccess(value: Unit)` would compile to `(Lkotlin/Unit;)V` and GetMethodID fails.
        if (type == KneType.UNIT) {
            line("        fun onSuccess() {")
        } else {
            line("        fun onSuccess(value: ${suspendParamType(type)}) {")
        }
        line("            try {")
        val resumed = if (type == KneType.UNIT) "Unit" else resumeExpr(module, type, "value")
        line("                cont.resume($resumed) {}")
        line("            } catch (_: IllegalStateException) {")
        line("                // continuation already cancelled from the JVM side")
        line("            } finally {")
        line("                lease.release()")
        line("            }")
        line("        }")
        line()
        line("        fun onError(message: String) {")
        line("            try {")
        line("                cont.resumeWithException(KotlinNativeException(message))")
        line("            } catch (_: IllegalStateException) {")
        line("            } finally {")
        line("                lease.release()")
        line("            }")
        line("        }")
        line()
        line("        fun onCancelled() {")
        line("            try {")
        line("                cont.cancel(CancellationException(\"cancelled natively\"))")
        line("            } catch (_: IllegalStateException) {")
        line("            } finally {")
        line("                lease.release()")
        line("            }")
        line("        }")
        line("    }")
    }

    /** Param type of the dispatcher's onSuccess/onNext for a native payload mapping. */
    private fun suspendParamType(type: KneType): String = when {
        type is KneType.NULLABLE -> when (val inner = type.inner) {
            is KneType.STRING -> "String?"
            is KneType.BYTE_ARRAY -> "ByteArray?"
            is KneType.BOOLEAN -> "Int"
            is KneType.INT, is KneType.LONG, is KneType.FLOAT, is KneType.DOUBLE -> "Long"
            is KneType.SHORT, is KneType.BYTE -> "Int"
            is KneType.ENUM -> "Int"
            is KneType.OBJECT, is KneType.INTERFACE -> "Long"
            is KneType.DATA_CLASS -> inner.simpleName + "?"
            is KneType.LIST -> jArrayParamType(inner.elementType) + "?"
            is KneType.SET -> jArrayParamType(inner.elementType) + "?"
            is KneType.MAP -> "Map<${inner.keyType.jvmTypeName}, ${inner.valueType.jvmTypeName}>?"
            else -> "Any?"
        }
        else -> when (type) {
            is KneType.INT -> "Int"
            is KneType.LONG -> "Long"
            is KneType.DOUBLE -> "Double"
            is KneType.FLOAT -> "Float"
            is KneType.BOOLEAN -> "Boolean"
            is KneType.BYTE -> "Byte"
            is KneType.SHORT -> "Short"
            is KneType.STRING -> "String"
            is KneType.BYTE_ARRAY -> "ByteArray"
            is KneType.ENUM -> "Int"
            is KneType.OBJECT, is KneType.INTERFACE -> "Long"
            is KneType.DATA_CLASS -> type.simpleName
            is KneType.LIST -> jArrayParamType(type.elementType)
            is KneType.SET -> jArrayParamType(type.elementType)
            is KneType.MAP -> "Map<${type.keyType.jvmTypeName}, ${type.valueType.jvmTypeName}>"
            is KneType.UNIT -> "Unit"
            else -> "Any?"
        }
    }

    private fun jArrayParamType(elemType: KneType): String = when (elemType) {
        is KneType.INT -> "IntArray"
        is KneType.LONG -> "LongArray"
        is KneType.DOUBLE -> "DoubleArray"
        is KneType.FLOAT -> "FloatArray"
        is KneType.SHORT -> "ShortArray"
        is KneType.BYTE -> "ByteArray"
        is KneType.BOOLEAN -> "BooleanArray"
        is KneType.ENUM -> "IntArray"
        is KneType.STRING -> "Array<String?>"
        is KneType.OBJECT, is KneType.INTERFACE -> "LongArray"
        is KneType.BYTE_ARRAY -> "Array<ByteArray?>"
        else -> "Array<Any?>"
    }

    /** Expression converting the dispatcher payload into the public suspend/flow value. */
    private fun resumeExpr(module: KneModule, type: KneType, value: String): String {
        if (type is KneType.NULLABLE) {
            return when (val inner = type.inner) {
                is KneType.STRING, is KneType.BYTE_ARRAY, is KneType.DATA_CLASS, is KneType.MAP -> value
                is KneType.BOOLEAN -> "if ($value < 0) null else $value != 0"
                is KneType.INT -> "if ($value != Long.MIN_VALUE) $value.toInt() else null"
                is KneType.LONG -> "if ($value != Long.MIN_VALUE) $value else null"
                is KneType.SHORT -> "if ($value != Int.MIN_VALUE) $value.toShort() else null"
                is KneType.BYTE -> "if ($value != Int.MIN_VALUE) $value.toByte() else null"
                is KneType.FLOAT -> "if ($value != Long.MIN_VALUE) Float.fromBits($value.toInt()) else null"
                is KneType.DOUBLE -> "if ($value != Long.MIN_VALUE) Double.fromBits($value) else null"
                is KneType.ENUM -> "if ($value >= 0) ${inner.simpleName}.entries[$value] else null"
                is KneType.OBJECT -> "if ($value != 0L) ${inner.simpleName}.fromNativeHandle($value) else null"
                is KneType.INTERFACE -> "if ($value != 0L) ${inner.simpleName}.fromNativeHandle($value) else null"
                is KneType.LIST -> "if ($value == null) null else ${collResumeExpr(inner.elementType, value, "List")}"
                is KneType.SET -> "if ($value == null) null else ${collResumeExpr(inner.elementType, value, "Set")}"
                else -> value
            }
        }
        return when (type) {
            is KneType.ENUM -> "${type.simpleName}.entries[$value]"
            is KneType.OBJECT -> "${type.simpleName}.fromNativeHandle($value)"
            is KneType.INTERFACE -> "${type.simpleName}.fromNativeHandle($value)"
            is KneType.LIST -> collResumeExpr(type.elementType, value, "List")
            is KneType.SET -> collResumeExpr(type.elementType, value, "Set")
            else -> value
        }
    }

    private fun collResumeExpr(elemType: KneType, value: String, collKind: String): String {
        val list = when (elemType) {
            is KneType.INT, is KneType.LONG, is KneType.DOUBLE, is KneType.FLOAT,
            is KneType.SHORT, is KneType.BYTE, is KneType.BOOLEAN -> "$value.toList()"
            is KneType.ENUM -> "$value.toList().map { ${elemType.simpleName}.entries[it] }"
            is KneType.STRING -> "$value.map { it ?: \"\" }"
            is KneType.OBJECT -> "$value.map { ${elemType.simpleName}.fromNativeHandle(it) }"
            is KneType.INTERFACE -> "$value.map { ${elemType.simpleName}.fromNativeHandle(it) }"
            is KneType.BYTE_ARRAY -> "$value.map { it ?: ByteArray(0) }"
            is KneType.DATA_CLASS -> "$value.map { it as ${elemType.simpleName} }"
            // Nested collections arrive as an Object[] of jarray elements (List<List<Int>> →
            // Object[] of int[]), so each element must be unpacked, never cast to java.util.List.
            is KneType.LIST -> "$value.map { ${nestedCollUnwrap(elemType.elementType, "it")} }"
            is KneType.SET -> "$value.map { ${nestedCollUnwrap(elemType.elementType, "it")} }"
            else -> "$value.toList()"
        }
        return if (collKind == "Set") "$list.toSet()" else list
    }

    // ── Flow dispatchers ─────────────────────────────────────────────────────

    /** Emits `KneFlow<Id>`: JNI callback object feeding a callbackFlow channel. */
    private fun StringBuilder.emitFlowDispatcher(module: KneModule, elemType: KneType) {
        val id = payloadId(elemType)
        val publicType = elemType.jvmTypeName
        line()
        line("    internal class KneFlow$id(")
        line("        private val channel: kotlinx.coroutines.channels.SendChannel<$publicType>,")
        line("        private val lease: Lease? = null,")
        line("    ) {")
        line("        @JvmField var jobId: Long = 0L")
        line("        private val released = java.util.concurrent.atomic.AtomicBoolean(false)")
        line()
        line("        /** Releases the owner's lease exactly once (native signals exactly one terminal event). */")
        line("        fun release() { if (released.compareAndSet(false, true)) lease?.release() }")
        line()
        // Flow<Unit> elements carry no payload: native calls `onNext()V`, so the JVM overload must
        // be parameterless (a `value: Unit` param would compile to `(Lkotlin/Unit;)V`).
        if (elemType == KneType.UNIT) {
            line("        fun onNext() {")
            line("            try {")
            line("                runBlocking { channel.send(Unit) }")
        } else {
            line("        fun onNext(value: ${suspendParamType(elemType)}) {")
            line("            try {")
            line("                runBlocking { channel.send(${resumeExpr(module, elemType, "value")}) }")
        }
        line("                KneNativeBindings._kneFlowCredit(jobId)")
        line("            } catch (_: Exception) {")
        line("                // channel closed: collection was cancelled")
        line("            }")
        line("        }")
        line()
        line("        fun onError(message: String) { channel.close(KotlinNativeException(message)); release() }")
        line()
        line("        fun onComplete() { channel.close(); release() }")
        line()
        line("        fun onCancelled() { channel.close(); release() }")
        line("    }")
    }

    /** Payload id shared with the native generator's naming. */
    private fun payloadId(type: KneType): String = when {
        type is KneType.NULLABLE -> "N" + payloadId(type.inner)
        else -> when (type) {
            is KneType.INT -> "Int"
            is KneType.LONG -> "Long"
            is KneType.DOUBLE -> "Double"
            is KneType.FLOAT -> "Float"
            is KneType.BOOLEAN -> "Boolean"
            is KneType.BYTE -> "Byte"
            is KneType.SHORT -> "Short"
            is KneType.STRING -> "String"
            is KneType.BYTE_ARRAY -> "Bytes"
            is KneType.UNIT -> "Void"
            is KneType.ENUM -> "E" + type.simpleName
            is KneType.OBJECT -> "H" + type.simpleName
            is KneType.INTERFACE -> "I" + type.simpleName
            is KneType.DATA_CLASS -> "D" + type.simpleName
            is KneType.LIST -> "L" + payloadId(type.elementType)
            is KneType.SET -> "S" + payloadId(type.elementType)
            is KneType.MAP -> "M" + payloadId(type.keyType) + "_" + payloadId(type.valueType)
            else -> "X"
        }
    }

