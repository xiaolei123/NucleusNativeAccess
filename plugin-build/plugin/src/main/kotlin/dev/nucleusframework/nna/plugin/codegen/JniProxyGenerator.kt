    // Class proxy
    // ══════════════════════════════════════════════════════════════════════════

    private fun StringBuilder.emitClassProxy(cls: KneClass, module: KneModule, pkg: String) {
        val n = cls.simpleName

        line("// Auto-generated by kotlin-native-export plugin. Do not modify.")
        line("package $pkg")
        line()
        line("import java.lang.ref.Cleaner")
        val classHasSuspend = cls.methods.any { it.isSuspend || it.returnType is KneType.FLOW } || cls.companionMethods.any { it.isSuspend }
        if (classHasSuspend) {
            line("import kotlinx.coroutines.suspendCancellableCoroutine")
            line("import kotlinx.coroutines.CancellableContinuation")
            line("import kotlinx.coroutines.channels.awaitClose")
            line("import kotlinx.coroutines.flow.Flow")
            line("import kotlinx.coroutines.flow.callbackFlow")
            line("import kotlinx.coroutines.runBlocking")
            line("import kotlinx.coroutines.CancellationException")
            line("import kotlin.coroutines.resume")
            line("import kotlin.coroutines.resumeWithException")
            line()
        }

        line("/**")
        line(" * JVM proxy for Kotlin/Native class [$n].")
        line(" * Dispatches every call into the native shared library via JNI (external fun).")
        line(" * Object lifecycle is managed via Java Cleaner (automatic GC) or explicit close().")
        line(" */")
        val isRoot = cls.superClass == null
        val hasSuperClass = cls.superClass != null

        val modifier = when {
            cls.isSealed -> "sealed "
            cls.isAbstract -> "abstract "
            cls.isOpen -> "open "
            else -> ""
        }

        val isInstantiable = !cls.isAbstract && !cls.isSealed
        val hasHierarchy = hasSuperClass || cls.isOpen || cls.isAbstract || cls.isSealed || cls.interfaces.isNotEmpty()

        val ctorVisibility = when {
            cls.isSealed -> "protected"
            hasHierarchy -> "internal"
            else -> "private"
        }

        val superParts = mutableListOf<String>()
        if (hasSuperClass) {
            superParts.add("${cls.superClass!!.substringAfterLast(".")}(handle)")
        } else {
            superParts.add("AutoCloseable")
        }
        cls.interfaces.forEach { ifaceFq -> superParts.add(ifaceFq.substringAfterLast(".")) }
        val superClause = superParts.joinToString(", ")

        val implementsInterface = cls.interfaces.isNotEmpty()
        val handleDecl = when {
            !isRoot -> "handle: Long"
            implementsInterface -> "override val handle: Long"
            hasHierarchy -> "val handle: Long"
            else -> "internal val handle: Long"
        }

        line("${modifier}class $n $ctorVisibility constructor($handleDecl) : $superClause {")
        if (isRoot) {
            line("    internal val _lease = KneRuntime.Lease(KneRuntime.disposer(handle))")
        }
        line()

        // ── companion ──
        line("    companion object {")
        if (isInstantiable) {
            line("        private val CLEANER = Cleaner.create()")
        }
        line("        private val _kneReg = KneRuntime.ensureNativesRegistered()")
        line()

        if (isInstantiable) {
            val ctorVariants = buildList {
                add(cls.constructor.params)
                val trailingDefaults = cls.constructor.params.reversed().takeWhile { it.hasDefault }.size
                for (drop in 1..trailingDefaults) add(cls.constructor.params.dropLast(drop))
            }
            ctorVariants.forEachIndexed { index, params ->
                val suffix = if (index == 0) "" else index.toString()
                val extParams = externalParamDeclList(params, leadingHandle = false)
                line("        @JvmStatic")
                line("        private external fun _kneNew$suffix($extParams): Long")
                line()

                val ctorParams = params.joinToString(", ") { "${it.name}: ${it.type.jvmTypeName}" }
                line("        operator fun invoke($ctorParams): $n {")
                line("            val h = _kneNew$suffix(${ctorCallArgs(params)})")
                line("            return fromNativeHandle(h)")
                line("        }")
                line()
            }

            // @JvmStatic + public is required by the JNI backend: the native side rebuilds the
            // proxy with CallStaticObjectMethodA(clazz, "fromNativeHandle", "(J)L...;"), which only
            // resolves for a real static method. A plain `internal fun` would compile to an
            // instance method with a mangled name (fromNativeHandle$module) and never be found.
            line("        @JvmStatic")
            line("        fun fromNativeHandle(h: Long): $n {")
            line("            val obj = $n(h)")
            line("            val lease = obj._lease")
            line("            CLEANER.register(obj) { lease.close() }")
            line("            return obj")
            line("        }")
            line()
        }

        // externals
        cls.methods.forEach { method ->
            when {
                method.isSuspend -> emitSuspendExternalDecl(method, indent = "        ")
                method.returnType is KneType.FLOW -> emitFlowExternalDecl(method, indent = "        ")
                else -> emitExternalDecl(fnName = method.name, params = method.params, withHandle = true, returnType = method.returnType, indent = "        ")
            }
        }
        cls.properties.forEach { prop -> emitPropertyExternalDecls(prop, indent = "        ") }
        cls.companionMethods.forEach { method ->
            emitExternalDecl(fnName = method.name, params = method.params, withHandle = false, returnType = method.returnType, indent = "        ", prefix = "Companion")
        }
        cls.companionProperties.forEach { prop -> emitCompanionPropertyExternalDecls(prop, indent = "        ") }

        // companion method/property public bodies (inside companion object)
        cls.companionMethods.forEach { method -> emitCompanionMethodBody(method) }
        cls.companionProperties.forEach { prop -> emitCompanionPropertyBody(prop) }

        line("    }")
        line()

        // ── instance members ──
        // Track parent method/property names for override detection
        val parentMembers = collectParentMembers(cls, module)
        val canHaveOverrides = cls.isOpen || cls.isAbstract || cls.isSealed || hasSuperClass
        cls.methods.forEach { method ->
            emitInstanceMethodBody(method, module, isOverride = method.name in parentMembers, parentIsOpen = canHaveOverrides && method.name !in parentMembers)
        }
        cls.properties.forEach { prop -> emitInstancePropertyBody(prop, isOverride = prop.name in parentMembers, parentIsOpen = canHaveOverrides && prop.name !in parentMembers) }

        if (isInstantiable && (isRoot || hasSuperClass)) {
            line("    override fun close() {")
            line("        _lease.close()")
            line("    }")
            line()
        }

        line("}")
    }

    // ── external declaration emitters ────────────────────────────────────────

    /** Collects method and property names from all ancestor classes for override detection. */
    private fun collectParentMembers(cls: KneClass, module: KneModule): Set<String> {
        val names = mutableSetOf<String>()
        var current = cls.superClass
        while (current != null) {
            val parent = module.classes.find { it.fqName == current }
            if (parent != null) {
                parent.methods.forEach { names.add(it.name) }
                parent.properties.forEach { names.add(it.name) }
                current = parent.superClass
            } else break
        }
        // Also collect interface members
        cls.interfaces.forEach { ifaceFq ->
            val iface = module.interfaces.find { it.fqName == ifaceFq }
            if (iface != null) {
                iface.methods.forEach { names.add(it.name) }
                iface.properties.forEach { names.add(it.name) }
            }
        }
        return names
    }

    private fun extName(name: String): String = "_kne" + name.replaceFirstChar { it.uppercaseChar() }

    /**
     * Builds an external-fun name from a prefix plus a member name, capitalizing the member so the
     * result matches the native side's `"$prefix" + name.replaceFirstChar { uppercase }` rule.
     *
     * `extName("Get$current")` would yield `_kneGetcurrent`; this yields `_kneGetCurrent`.
     */
    private fun extName(prefix: String, member: String): String =
        "_kne" + prefix + member.replaceFirstChar { it.uppercaseChar() }

    /** Declared external params for the JVM side (DCs flatten; maps expand into keys/values). */
    private fun externalParamDeclList(params: List<KneParam>, leadingHandle: Boolean): String {
        val parts = mutableListOf<String>()
        if (leadingHandle) parts.add("handle: Long")
        params.forEach { p ->
            val dc = JniTypes.extractDataClass(p.type)
            if (dc != null) {
                if (p.type is KneType.NULLABLE) parts.add("${p.name}_isNull: Int")
                dcFlatExternalParams(dc, p.name).forEach { (fname, ftype) ->
                    parts.add("$fname: $ftype")
                }
            } else {
                JniTypes.expandExternalParams(p.name, p.type).forEach { (ename, etype) ->
                    parts.add("$ename: $etype")
                }
            }
        }
        return parts.joinToString(", ")
    }

    /** Flat external params for a DC: map fields expand into keys/values array pairs. */
    private fun dcFlatExternalParams(dc: KneType.DATA_CLASS, name: String): List<Pair<String, String>> =
        JniTypes.flattenDataClassFields(dc, name).flatMap { (fname, ftype) ->
            when {
                ftype is KneType.MAP -> listOf(
                    "${fname}_keys" to JniTypes.arrayParamType(ftype.keyType),
                    "${fname}_values" to JniTypes.arrayParamType(ftype.valueType),
                )
                else -> listOf(fname to extParamType(ftype))
            }
        }

    /** Call args for a DC in the exact order of [dcFlatExternalParams]. */
    private fun dcFlatCallArgs(dc: KneType.DATA_CLASS, name: String, nullable: Boolean): List<String> {
        // For value access we need the ORIGINAL field names, not the prefixed external param names
        fun originalFields(dc: KneType.DATA_CLASS, prefix: String): List<Pair<String, KneType>> =
            dc.fields.map { f ->
                val prefixed = "${prefix}_${f.name}"
                if (f.type is KneType.DATA_CLASS) f.name to KneType.DATA_CLASS(f.type.fqName, f.type.simpleName, f.type.fields) // marker for recursion
                else f.name to f.type
            }
        fun accessPath(prefix: String, fieldName: String): String = "$prefix.$fieldName"
        // Build the args using the dc.fields (original names) matching flattenDataClassFields order
        fun buildArgs(dc: KneType.DATA_CLASS, objName: String): List<List<Pair<String, KneType>>> {
            // For simple (non-nested) DCs this is straightforward
            return listOf(dc.fields.map { it.name to it.type })
        }
        // Just use dc.fields directly (original names), matching the flatten order for non-nested case
        // For nested DCs, the field access is obj.nested.field
        val result = mutableListOf<String>()
        fun addFields(dc: KneType.DATA_CLASS, objPath: String) {
            dc.fields.forEach { f ->
                val fieldPath = "$objPath.${f.name}"
                when {
                    f.type is KneType.DATA_CLASS -> addFields(f.type, fieldPath)
                    f.type is KneType.MAP -> {
                        result.add(packCollectionArg("$fieldPath.keys", f.type.keyType, setWrap = false, nullable = false))
                        result.add(packCollectionArg("$fieldPath.values", f.type.valueType, setWrap = false, nullable = false))
                    }
                    else -> result.add(plainCallArg(fieldPath, f.type))
                }
            }
        }
        fun addNullableFields(dc: KneType.DATA_CLASS, objName: String) {
            dc.fields.forEach { f ->
                val fieldPath = "$objName?.${f.name}"
                when {
                    f.type is KneType.DATA_CLASS -> { /* nested nullable DC not common */ }
                    f.type is KneType.MAP -> {
                        result.add(packCollectionArg("$fieldPath?.keys", f.type.keyType, setWrap = false, nullable = true))
                        result.add(packCollectionArg("$fieldPath?.values", f.type.valueType, setWrap = false, nullable = true))
                    }
                    else -> result.add(nullableDcFieldArg(objName, f.name, f.type))
                }
            }
        }
        if (nullable) addNullableFields(dc, name) else addFields(dc, name)
        return result
    }

    private fun extParamType(type: KneType): String = when {
        JniTypes.extractDataClass(type) != null -> error("DC fields must be flat here")
        type is KneType.NULLABLE -> when (type.inner) {
            is KneType.STRING -> "String?"
            is KneType.BYTE_ARRAY -> "ByteArray?"
            is KneType.LIST -> JniTypes.arrayParamType(type.inner.elementType) + "?"
            is KneType.SET -> JniTypes.arrayParamType(type.inner.elementType) + "?"
            is KneType.MAP -> "Map<${type.inner.keyType.jvmTypeName}, ${type.inner.valueType.jvmTypeName}>?"
            is KneType.FUNCTION -> "Any?"
            else -> JniTypes.externalParamType(type)
        }
        else -> JniTypes.externalParamType(type)
    }

    /** External fun return type for a KneType. */
    private fun extReturnType(type: KneType): String = when {
        type == KneType.UNIT -> "Unit"
        JniTypes.extractDataClass(type) != null -> {
            val dc = JniTypes.extractDataClass(type)!!
            dc.simpleName + if (type is KneType.NULLABLE) "?" else ""
        }
        type is KneType.ENUM -> "Int"
        type is KneType.OBJECT -> "Long"
        type is KneType.INTERFACE -> "Long"
        type is KneType.NULLABLE -> when (type.inner) {
            is KneType.STRING -> "String?"
            is KneType.BYTE_ARRAY -> "ByteArray?"
            is KneType.LIST -> JniTypes.arrayParamType(type.inner.elementType) + "?"
            is KneType.SET -> JniTypes.arrayParamType(type.inner.elementType) + "?"
            is KneType.MAP -> "Map<${type.inner.keyType.jvmTypeName}, ${type.inner.valueType.jvmTypeName}>?"
            is KneType.ENUM -> "Int"
            // Native returns an opaque StableRef handle for a lambda; see fnInvokeWrapExpr.
            is KneType.FUNCTION -> "Long"
            else -> JniTypes.externalParamType(type)
        }
        type is KneType.LIST || type is KneType.SET ->
            JniTypes.arrayParamType(JniTypes.unwrapNullable(type).let { t ->
                if (t is KneType.LIST) t.elementType else (t as KneType.SET).elementType
            })
        type is KneType.MAP -> "Map<${type.keyType.jvmTypeName}, ${type.valueType.jvmTypeName}>"
        type is KneType.FUNCTION -> "Long"
        else -> type.jvmTypeName
    }

    /**
     * Emits an `external fun` declaration. [fnName] is the raw member name; [prefix] distinguishes
     * companion members (`Companion`) from instance ones while keeping the member capitalized the
     * same way the native registration does.
     */
    private fun StringBuilder.emitExternalDecl(
        fnName: String,
        params: List<KneParam>,
        withHandle: Boolean,
        returnType: KneType,
        indent: String,
        prefix: String = "",
    ) {
        val extParams = externalParamDeclList(params, leadingHandle = withHandle)
        line("${indent}@JvmStatic")
        line("${indent}private external fun ${extName(prefix, fnName)}($extParams): ${extReturnType(returnType)}")
        line()
    }

    private fun StringBuilder.emitSuspendExternalDecl(fn: KneFunction, indent: String) {
        val extParams = externalParamDeclList(fn.params, leadingHandle = true)
        line("${indent}@JvmStatic")
        line("${indent}private external fun ${extName(fn.name)}Async($extParams, completion: Any?): Long")
        line()
    }

    private fun StringBuilder.emitFlowExternalDecl(fn: KneFunction, indent: String) {
        val extParams = externalParamDeclList(fn.params, leadingHandle = true)
        line("${indent}@JvmStatic")
        line("${indent}private external fun ${extName(fn.name)}Flow($extParams, callback: Any?): Long")
        line()
    }

    private fun StringBuilder.emitPropertyExternalDecls(prop: KneProperty, indent: String) {
        line("${indent}@JvmStatic")
        line("${indent}private external fun ${extName("Get", prop.name)}(handle: Long): ${extReturnType(prop.type)}")
        line()
        if (prop.mutable) {
            val valueParams = externalParamDeclList(listOf(KneParam("value", prop.type)), leadingHandle = true)
            line("${indent}@JvmStatic")
            line("${indent}private external fun ${extName("Set", prop.name)}($valueParams)")
            line()
        }
    }

    private fun StringBuilder.emitCompanionPropertyExternalDecls(prop: KneProperty, indent: String) {
        line("${indent}@JvmStatic")
        line("${indent}private external fun ${extName("CompanionGet", prop.name)}(): ${extReturnType(prop.type)}")
        line()
        if (prop.mutable) {
            val valueParams = externalParamDeclList(listOf(KneParam("value", prop.type)), leadingHandle = false)
            line("${indent}@JvmStatic")
            line("${indent}private external fun ${extName("CompanionSet", prop.name)}($valueParams)")
            line()
        }
    }

    // ── call-argument packing (JVM value → external params) ──────────────────

    /** Conversion of a plain (non-DC) value at an external call site (multi-arg for maps). */
    private fun callArgExpr(name: String, type: KneType): List<String> = when {
        JniTypes.extractDataClass(type) != null -> {
            val dc = JniTypes.extractDataClass(type)!!
            if (type is KneType.NULLABLE) {
                // Native reads this as `_isNull`: 1 means "no value, build null".
                listOf("if ($name == null) 1 else 0") +
                    dcFlatCallArgs(dc, name, nullable = true)
            } else {
                dcFlatCallArgs(dc, name, nullable = false)
            }
        }
        type is KneType.NULLABLE && type.inner is KneType.MAP -> {
            val m = type.inner as KneType.MAP
            listOf(
                packCollectionArg("$name.keys", m.keyType, setWrap = false, nullable = true),
                packCollectionArg("$name.values", m.valueType, setWrap = false, nullable = true),
            )
        }
        type is KneType.MAP -> listOf(
            packCollectionArg("$name.keys", type.keyType, setWrap = false, nullable = false),
            packCollectionArg("$name.values", type.valueType, setWrap = false, nullable = false),
        )
        else -> listOf(plainCallArg(name, type))
    }

    /** Conversion of a plain (non-DC, non-map) value at an external call site. */
    private fun plainCallArg(expr: String, type: KneType): String = when (type) {
        is KneType.ENUM -> "$expr.ordinal"
        is KneType.OBJECT -> "$expr.handle"
        is KneType.INTERFACE -> "$expr.handle"
        // Native strings are NUL-terminated on the wire (GetStringUTFChars protocol): reject
        // embedded NULs up front, mirroring the FFM backend's KneRuntime.cstr validation.
        is KneType.STRING -> "KneRuntime.checkString($expr)"
        is KneType.LIST -> packCollectionArg(expr, type.elementType, setWrap = false, nullable = false)
        is KneType.SET -> packCollectionArg(expr, type.elementType, setWrap = true, nullable = false)
        is KneType.FUNCTION -> "KneRuntime.KneFn${callbackId(type)}($expr)"
        is KneType.NULLABLE -> when (type.inner) {
            is KneType.FUNCTION -> "$expr?.let { KneRuntime.KneFn${callbackId(type.inner as KneType.FUNCTION)}(it) }"
            is KneType.STRING -> "$expr?.let { KneRuntime.checkString(it) }"
            is KneType.LIST -> packCollectionArg(expr, type.inner.elementType, setWrap = false, nullable = true)
            is KneType.SET -> packCollectionArg(expr, type.inner.elementType, setWrap = true, nullable = true)
            else -> expr
        }
        else -> expr
    }

    /** A flattened DC field call arg (value comes from a non-null DC object). */
    private fun nullableDcFieldArg(dcName: String, fieldName: String, fieldType: KneType): String {
        val path = "$dcName?.$fieldName"
        return when (fieldType) {
            is KneType.STRING -> "$path?.let { KneRuntime.checkString(it) } ?: \"\""
            is KneType.BOOLEAN -> "if ($path == true) 1 else 0"
            is KneType.BYTE -> "$path ?: 0.toByte()"
            is KneType.SHORT -> "$path ?: 0.toShort()"
            is KneType.INT -> "$path ?: 0"
            is KneType.LONG -> "$path ?: 0L"
            is KneType.FLOAT -> "$path ?: 0f"
            is KneType.DOUBLE -> "$path ?: 0.0"
            is KneType.ENUM -> "$path?.ordinal ?: 0"
            is KneType.OBJECT, is KneType.INTERFACE -> "$path?.handle ?: 0L"
            is KneType.BYTE_ARRAY -> "$path ?: ByteArray(0)"
            is KneType.LIST -> "$path ?: emptyList()"
            is KneType.SET -> "$path ?: emptySet()"
            is KneType.MAP -> "$path ?: emptyMap()"
            is KneType.DATA_CLASS -> path!! // nested nullability not flattened across null boundary
            else -> path ?: "null"
        }
    }

    /** Packs a List/Set<T> param into the external array type. */
    private fun packCollectionArg(expr: String, elemType: KneType, setWrap: Boolean, nullable: Boolean): String {
        val src = if (setWrap) "$expr.toList()" else expr
        val body = when (elemType) {
            is KneType.INT -> "$src.toIntArray()"
            is KneType.LONG -> "$src.toLongArray()"
            is KneType.DOUBLE -> "$src.toDoubleArray()"
            is KneType.FLOAT -> "$src.toFloatArray()"
            is KneType.SHORT -> "$src.toShortArray()"
            is KneType.BYTE -> "$src.toByteArray()"
            is KneType.BOOLEAN -> "$src.toBooleanArray()"
            is KneType.ENUM -> "IntArray($src.size) { $src[it].ordinal }"
            is KneType.STRING -> "run { val _a = arrayOfNulls<String>($src.size); $src.forEachIndexed { i, s -> _a[i] = KneRuntime.checkString(s) }; _a }"
            is KneType.OBJECT -> "LongArray($src.size) { $src[it].handle }"
            is KneType.INTERFACE -> "LongArray($src.size) { $src[it].handle }"
            is KneType.BYTE_ARRAY -> "run { val _a = arrayOfNulls<ByteArray>($src.size); $src.forEachIndexed { i, b -> _a[i] = b }; _a }"
            is KneType.DATA_CLASS -> "run { val _a = arrayOfNulls<Any>($src.size); $src.forEachIndexed { i, v -> _a[i] = v }; _a }"
            is KneType.LIST -> "run { val _a = arrayOfNulls<Any>($src.size); $src.forEachIndexed { i, v -> _a[i] = ${packNestedElem("v", elemType.elementType)} }; _a }"
            is KneType.SET -> "run { val _a = arrayOfNulls<Any>($src.size); $src.forEachIndexed { i, v -> _a[i] = ${packNestedElem("v", elemType.elementType)} }; _a }"
            is KneType.MAP -> "run { val _a = arrayOfNulls<Any>($src.size); $src.forEachIndexed { i, v -> _a[i] = java.util.HashMap(v) }; _a }"
            else -> "$src.toTypedArray()"
        }
        return if (nullable) "$expr?.let { $body }" else body
    }

    private fun packNestedElem(expr: String, elemType: KneType): String = when (elemType) {
        is KneType.LIST -> packCollectionArg(expr, elemType.elementType, setWrap = false, nullable = false)
        is KneType.SET -> packCollectionArg(expr, elemType.elementType, setWrap = true, nullable = false)
        is KneType.MAP -> "java.util.HashMap($expr)"
        else -> packCollectionArg(expr, elemType, setWrap = false, nullable = false)
    }

    /** Call args string for a constructor invocation (no leading handle). */
    private fun ctorCallArgs(params: List<KneParam>): String =
        params.flatMap { callArgExpr(it.name, it.type) }.joinToString(", ")

    /** All call args for a function, optionally with leading handle. */
    private fun allCallArgs(params: List<KneParam>, handleExpr: String?): String = buildString {
        if (handleExpr != null) append(handleExpr)
        params.forEach { p ->
            if (isNotEmpty()) append(", ")
            append(callArgExpr(p.name, p.type).joinToString(", "))
        }
    }

    // ── return unwrapping (external result → public value) ───────────────────

    /** Emits a call whose result is unwrapped into the public return value. */
    private fun StringBuilder.emitCallableBody(
        fn: KneFunction,
        module: KneModule,
        indent: String,
        receiverExpr: String?,
        externalRef: String,
    ) {
        val args = allCallArgs(fn.params, receiverExpr)
        val call = "$externalRef($args)"
        val usesLease = receiverExpr == "handle"

        // Proxy objects passed as arguments are leased for the call: acquire() throws when the
        // argument was already closed (fails cleanly on the caller side instead of handing a stale
        // handle to native) and release() defers disposal until native stops using it.
        val leasedArgs = fn.params.filter {
            it.type is KneType.OBJECT || (it.type is KneType.NULLABLE && it.type.inner is KneType.OBJECT)
        }
        var inner = indent
        leasedArgs.forEach { p ->
            val leaseExpr = if (p.type is KneType.NULLABLE) "${p.name}?._lease" else "${p.name}._lease"
            line("$inner" + "KneRuntime.leased($leaseExpr) {")
            inner += "    "
        }

        if (fn.returnType == KneType.UNIT) {
            if (usesLease) {
                line("${inner}_lease.use {")
                line("$inner    $call")
                line("$inner}")
            } else {
                line("$inner$call")
            }
        } else {
            val unwrap = unwrapReturnExpr(fn.returnType)
            if (usesLease) {
                line("${inner}_lease.use {")
                line("$inner    val _r = $call")
                line("$inner    return $unwrap")
                line("$inner}")
            } else {
                line("${inner}val _r = $call")
                line("${inner}return $unwrap")
            }
        }

        repeat(leasedArgs.size) { line("$indent}") }
    }

    /** Expression referencing the local `_r` (raw external result) producing the public value. */
    private fun unwrapReturnExpr(type: KneType): String = when (val t = JniTypes.unwrapNullable(type)) {
        is KneType.ENUM ->
            if (type is KneType.NULLABLE) "if (_r >= 0) ${t.simpleName}.entries[_r] else null"
            else "${t.simpleName}.entries[_r]"
        is KneType.OBJECT ->
            if (type is KneType.NULLABLE) "if (_r != 0L) ${t.simpleName}.fromNativeHandle(_r) else null"
            else "${t.simpleName}.fromNativeHandle(_r)"
        is KneType.INTERFACE ->
            if (type is KneType.NULLABLE) "if (_r != 0L) ${t.simpleName}.fromNativeHandle(_r) else null"
            else "${t.simpleName}.fromNativeHandle(_r)"
        is KneType.LIST ->
            if (type is KneType.NULLABLE) "if (_r == null) null else ${collUnwrap(t.elementType, "List")}"
            else collUnwrap(t.elementType, "List")
        is KneType.SET ->
            if (type is KneType.NULLABLE) "if (_r == null) null else ${collUnwrap(t.elementType, "Set")}"
            else collUnwrap(t.elementType, "Set")
        is KneType.BOOLEAN ->
            if (type is KneType.NULLABLE) "if (_r < 0) null else _r != 0"
            else "_r"
        is KneType.INT ->
            if (type is KneType.NULLABLE) "if (_r != Long.MIN_VALUE) _r.toInt() else null"
            else "_r"
        is KneType.LONG ->
            if (type is KneType.NULLABLE) "if (_r != Long.MIN_VALUE) _r else null"
            else "_r"
        is KneType.SHORT ->
            if (type is KneType.NULLABLE) "if (_r != Int.MIN_VALUE) _r.toShort() else null"
            else "_r"
        is KneType.BYTE ->
            if (type is KneType.NULLABLE) "if (_r != Int.MIN_VALUE) _r.toByte() else null"
            else "_r"
        is KneType.FLOAT ->
            if (type is KneType.NULLABLE) "if (_r != Long.MIN_VALUE) Float.fromBits(_r.toInt()) else null"
            else "_r"
        is KneType.DOUBLE ->
            if (type is KneType.NULLABLE) "if (_r != Long.MIN_VALUE) Double.fromBits(_r) else null"
            else "_r"
        is KneType.FUNCTION ->
            if (type is KneType.NULLABLE) fnInvokeWrapExpr(t, nullable = true)
            else fnInvokeWrapExpr(t)
        else -> "_r"
    }

    /**
     * Wraps a native lambda handle (`_r`) in a real Kotlin function value whose body calls the
     * `KneNativeBindings._kneInvokeFn<id>` bridge registered on the native side.
     */
    private fun fnInvokeWrapExpr(fnType: KneType.FUNCTION, nullable: Boolean = false): String {
        val id = JniTypes.functionId(fnType)
        val lambdaParams = fnType.paramTypes.indices.joinToString(", ") { "_p$it" }
        val callArgs = buildList {
            add("_r")
            fnType.paramTypes.forEachIndexed { i, t ->
                add(
                    when {
                        t is KneType.ENUM -> "_p$i.ordinal"
                        t is KneType.OBJECT || t is KneType.INTERFACE -> "_p$i.handle"
                        t is KneType.STRING -> "KneRuntime.checkString(_p$i)"
                        else -> "_p$i"
                    }
                )
            }
        }.joinToString(", ")
        val body = when (fnType.returnType) {
            KneType.UNIT -> "KneNativeBindings._kneInvokeFn$id($callArgs); Unit"
            else -> "(KneNativeBindings._kneInvokeFn$id($callArgs)) as ${fnType.returnType.jvmTypeName}"
        }
        val wrapped = "{ $lambdaParams -> $body }"
        return if (nullable) "if (_r == 0L) null else $wrapped" else wrapped
    }

    /** Expression producing a Kotlin List/Set from the raw `_r` jarray. */
    private fun collUnwrap(elemType: KneType, collKind: String): String {
        val list = when (elemType) {
            is KneType.INT, is KneType.LONG, is KneType.DOUBLE, is KneType.FLOAT,
            is KneType.SHORT, is KneType.BYTE, is KneType.BOOLEAN -> "_r.toList()"
            is KneType.ENUM -> "_r.toList().map { ${elemType.simpleName}.entries[it] }"
            is KneType.STRING -> "_r.map { it ?: \"\" }"
            is KneType.OBJECT -> "_r.map { ${elemType.simpleName}.fromNativeHandle(it) }"
            is KneType.INTERFACE -> "_r.map { ${elemType.simpleName}.fromNativeHandle(it) }"
            is KneType.BYTE_ARRAY -> "_r.map { it ?: ByteArray(0) }"
            is KneType.DATA_CLASS -> "_r.map { it as ${elemType.simpleName} }"
            // Nested collections cross as an Object[] of jarray elements (e.g. List<List<Int>>
            // arrives as Object[] of int[]), so each element has to be unpacked, not cast.
            is KneType.LIST -> "_r.map { ${nestedCollUnwrap(elemType.elementType, "it")} }"
            is KneType.SET -> "_r.map { ${nestedCollUnwrap(elemType.elementType, "it")} }"
            else -> "_r.toList()"
        }
        return if (collKind == "Set") "$list.toSet()" else list
    }

    /** Converts one packed jarray element (`Any?`) inside a nested collection into a Kotlin value. */
    private fun nestedCollUnwrap(elemType: KneType, expr: String): String = when (elemType) {
        is KneType.INT -> "($expr as IntArray).toList()"
        is KneType.LONG -> "($expr as LongArray).toList()"
        is KneType.DOUBLE -> "($expr as DoubleArray).toList()"
        is KneType.FLOAT -> "($expr as FloatArray).toList()"
        is KneType.SHORT -> "($expr as ShortArray).toList()"
        is KneType.BYTE -> "($expr as ByteArray).toList()"
        is KneType.BOOLEAN -> "($expr as BooleanArray).toList()"
        is KneType.ENUM -> "($expr as IntArray).toList().map { ${elemType.simpleName}.entries[it] }"
        is KneType.STRING -> "($expr as Array<*>).map { it as String }"
        is KneType.OBJECT -> "($expr as LongArray).toList().map { ${elemType.simpleName}.fromNativeHandle(it) }"
        is KneType.INTERFACE -> "($expr as LongArray).toList().map { ${elemType.simpleName}.fromNativeHandle(it) }"
        is KneType.LIST -> "($expr as Array<*>).map { ${nestedCollUnwrap(elemType.elementType, "it")} }"
        is KneType.SET -> "($expr as Array<*>).map { ${nestedCollUnwrap(elemType.elementType, "it")} }"
        else -> "($expr as List<Any?>)"
    }

    // ── instance member bodies ───────────────────────────────────────────────

    private fun StringBuilder.emitInstanceMethodBody(fn: KneFunction, module: KneModule, isOverride: Boolean = false, parentIsOpen: Boolean = false) {
        val publicParams = fn.params.joinToString(", ") { "${it.name}: ${it.type.jvmTypeName}" }
        val retDecl = if (fn.returnType == KneType.UNIT) "" else ": ${fn.returnType.jvmTypeName}"
        val suspendMod = if (fn.isSuspend) "suspend " else ""
        val mod = when {
            isOverride -> "override "
            parentIsOpen -> "open "
            else -> ""
        }
        line("    ${mod}${suspendMod}fun ${fn.name}($publicParams)$retDecl {")
        when {
            fn.isSuspend -> emitSuspendBody(fn)
            fn.returnType is KneType.FLOW -> emitFlowBody(fn)
            else -> emitCallableBody(fn, module, indent = "        ", receiverExpr = "handle", externalRef = extName(fn.name))
        }
        line("    }")
        line()
    }

    private fun StringBuilder.emitSuspendBody(fn: KneFunction) {
        val id = payloadId(fn.returnType)
        val args = allCallArgs(fn.params, "handle") + ", KneRuntime.KneSuspend$id(cont, _lease)"
        // Once the async call is dispatched, the completer (KneSuspend$id) is the lease's sole
        // owner: it releases exactly once in its finally, whether it completes, errors, or runs
        // after a JVM-side cancellation. The wrapper releases only when the dispatch itself
        // failed — no completer will ever fire in that case. Releasing unconditionally would
        // double-release on error/cancellation completions: the lease state underflows below
        // zero (reads as "closed" on every later call) and, worse, an undercounted in-flight
        // counter lets close() dispose the native ref while other calls are still using it.
        line("        _lease.acquire()")
        line("        var _kneDispatched = false")
        line("        try {")
        line("            return suspendCancellableCoroutine { cont ->")
        line("                val job = ${extName(fn.name)}Async($args)")
        line("                _kneDispatched = true")
        line("                cont.invokeOnCancellation { KneNativeBindings._kneCancelJob(job) }")
        line("            }")
        line("        } catch (t: Throwable) {")
        line("            if (!_kneDispatched) _lease.release()")
        line("            throw t")
        line("        }")
    }

    private fun StringBuilder.emitFlowBody(fn: KneFunction) {
        val elemType = (fn.returnType as KneType.FLOW).elementType
        val id = payloadId(elemType)
        // Lease is acquired when collection starts (mirrors the FFM backend's `flow { }` body):
        // acquire() rejects closed owners before the handle ever reaches native — otherwise a flow
        // started on a closed object dereferences a disposed StableRef and dies with a native NPE.
        // The dispatcher releases it on the single terminal event (onComplete/onError/onCancelled).
        line("        return callbackFlow {")
        line("            _lease.acquire()")
        line("            val _kneCb = KneRuntime.KneFlow$id(channel, _lease)")
        line("            val job = try {")
        line("                ${extName(fn.name)}Flow(${allCallArgs(fn.params, "handle")}, _kneCb)")
        line("            } catch (t: Throwable) {")
        line("                _lease.release()")
        line("                throw t")
        line("            }")
        line("            _kneCb.jobId = job")
        line("            awaitClose { KneNativeBindings._kneCancelJob(job) }")
        line("        }")
    }

    private fun StringBuilder.emitInstancePropertyBody(prop: KneProperty, isOverride: Boolean = false, parentIsOpen: Boolean = false) {
        val mod = when {
            isOverride -> "override "
            parentIsOpen -> "open "
            else -> ""
        }
        if (prop.mutable) {
            line("    $mod var ${prop.name}: ${prop.type.jvmTypeName}")
            line("        get() = _lease.use { val _r = ${extName("Get", prop.name)}(handle); ${unwrapReturnExpr(prop.type)} }")
            line("        set(value) {")
            line("            _lease.use {")
            line("                ${extName("Set", prop.name)}(${allCallArgs(listOf(KneParam("value", prop.type)), "handle")})")
            line("            }")
            line("        }")
        } else {
            line("    $mod val ${prop.name}: ${prop.type.jvmTypeName}")
            line("        get() = _lease.use { val _r = ${extName("Get", prop.name)}(handle); ${unwrapReturnExpr(prop.type)} }")
        }
        line()
    }

    private fun StringBuilder.emitCompanionMethodBody(fn: KneFunction) {
        val publicParams = fn.params.joinToString(", ") { "${it.name}: ${it.type.jvmTypeName}" }
        val retDecl = if (fn.returnType == KneType.UNIT) "" else ": ${fn.returnType.jvmTypeName}"
        line("    fun ${fn.name}($publicParams)$retDecl {")
        emitCallableBody(fn, module = KneModule("", emptySet(), emptyList(), emptyList(), emptyList(), emptyList()), indent = "        ", receiverExpr = null, externalRef = extName("Companion", fn.name))
        line("    }")
        line()
    }

    private fun StringBuilder.emitCompanionPropertyBody(prop: KneProperty) {
        if (prop.mutable) {
            line("    var ${prop.name}: ${prop.type.jvmTypeName}")
            line("        get() { val _r = ${extName("CompanionGet", prop.name)}(); return ${unwrapReturnExpr(prop.type)} }")
            line("        set(value) { ${extName("CompanionSet", prop.name)}(${allCallArgs(listOf(KneParam("value", prop.type)), null)}) }")
        } else {
            line("    val ${prop.name}: ${prop.type.jvmTypeName}")
            line("        get() { val _r = ${extName("CompanionGet", prop.name)}(); return ${unwrapReturnExpr(prop.type)} }")
        }
        line()
    }

    private fun collectCallbackSignatures(module: KneModule): Set<KneType.FUNCTION> {
        val signatures = mutableSetOf<KneType.FUNCTION>()
        fun scanParams(params: List<KneParam>) {
            params.forEach { p ->
                if (p.type is KneType.FUNCTION) signatures.add(p.type)
                else if (p.type is KneType.NULLABLE && (p.type as KneType.NULLABLE).inner is KneType.FUNCTION)
                    signatures.add((p.type as KneType.NULLABLE).inner as KneType.FUNCTION)
            }
        }
        module.classes.forEach { cls ->
            cls.methods.forEach { scanParams(it.params) }
            cls.companionMethods.forEach { scanParams(it.params) }
        }
        module.functions.forEach { scanParams(it.params) }
        return signatures
    }

    private fun callbackId(fnType: KneType.FUNCTION): String {
        fun sanitize(s: String) = s.replace("<", "_").replace(">", "").replace(", ", "_").replace("?", "N")
        val params = fnType.paramTypes.joinToString("_") { sanitize(it.jvmTypeName) }
        val ret = sanitize(fnType.returnType.jvmTypeName)
        return "${params.ifEmpty { "Void" }}_to_$ret"
    }
}

/** Small helper for uniform line emission. */
private fun StringBuilder.line(text: String) {
    appendLine(text)
}

/** Blank line. */
private fun StringBuilder.line() {
    appendLine()
}
