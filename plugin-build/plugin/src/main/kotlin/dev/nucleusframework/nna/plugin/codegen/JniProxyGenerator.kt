    private fun StringBuilder.emitFunctionObject(fns: List<KneFunction>, objectName: String, module: KneModule, pkg: String) {
        line("// Auto-generated by kotlin-native-export plugin. Do not modify.")
        line("package $pkg")
        line()
        emitJniFileImports(fns.any { it.isSuspend }, fns.any { it.returnType is KneType.FLOW })
        line()
        line("object $objectName {")
        line("    private val _kneReg = KneRuntime.ensureNativesRegistered()")
        line()

        fns.forEach { fn ->
            when {
                fn.isSuspend -> line("    // JNI backend does not support suspend top-level functions yet: ${fn.name}")
                fn.returnType is KneType.FLOW -> line("    // JNI backend does not support Flow top-level functions yet: ${fn.name}")
                else -> {
                    val extParams = externalParamDeclList(fn.params, leadingHandle = false)
                    line("    @JvmStatic")
                    line("    private external fun ${extName(fn.name)}($extParams): ${extReturnType(fn.returnType)}")
                    line()
                }
            }
        }
        fns.forEach { fn ->
            if (fn.isSuspend || fn.returnType is KneType.FLOW) return@forEach
            emitCallableBody(fn, module, indent = "    ", receiverExpr = null, externalRef = extName(fn.name))
        }
        line("}")
    }

    private fun StringBuilder.emitExtensionsFile(functions: List<KneFunction>, module: KneModule, pkg: String) {
        line("// Auto-generated by kotlin-native-export plugin. Do not modify.")
        line("package $pkg")
        line()
        emitJniFileImports(functions.any { it.isSuspend }, functions.any { it.returnType is KneType.FLOW })
        line()
        line("internal object KneExt {")
        line("    private val _kneReg = KneRuntime.ensureNativesRegistered()")
        line()
        functions.forEach { fn ->
            if (fn.isSuspend || fn.returnType is KneType.FLOW) return@forEach
            val extParams = externalParamDeclList(fn.params, leadingHandle = false)
            val fullParams = "receiverHandle: Long" + (if (extParams.isEmpty()) "" else ", $extParams")
            line("    @JvmStatic")
            line("    external fun ${extName("Ext", fn.name)}($fullParams): ${extReturnType(fn.returnType)}")
            line()
        }
        line("}")
        line()

        functions.forEach { fn ->
            val receiverType = fn.receiverType ?: return@forEach
            if (fn.isSuspend || fn.returnType is KneType.FLOW) return@forEach
            val receiverSimple = when (receiverType) {
                is KneType.OBJECT -> receiverType.simpleName
                is KneType.INTERFACE -> receiverType.simpleName
                else -> return@forEach
            }
            val params = fn.params.joinToString(", ") { "${it.name}: ${it.type.jvmTypeName}" }
            val retDecl = if (fn.returnType == KneType.UNIT) "" else ": ${fn.returnType.jvmTypeName}"
            line("fun $receiverSimple.${fn.name}($params)$retDecl {")
            emitCallableBody(fn, module, indent = "    ", receiverExpr = "receiverHandle = this.handle", externalRef = "KneExt." + extName("Ext", fn.name))
            line("}")
            line()
        }
    }

